import LocalizedStrings from 'react-localization';
import type { Language } from '../api/types';

export const supportedLanguages = [
	{ code: "en", name: "English", flag: '🇺🇸' },
	{ code: "lt", name: "Lietuvių", flag: '🇱🇹' },
	{ code: "ru", name: "Русский", flag: '🇷🇺' },
];

export const LANGUAGE_STORAGE_KEY = 'catalog_language';

export function getLocalizedField(language: string, fields: {language: Language, field: string}[]) {
	if(fields.length == 0)
		return null;

	const filtered = fields.filter(x => x.language.code === language);

	if(filtered.length != 0)
		return filtered[0];

	const fallback = fields.filter(x => x.language.code === 'en');

	if(fallback.length != 0)
		return fallback[0];

	return fields[0];
}

export function getSavedLanguage(): string {
	const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);

	if (saved && supportedLanguages.some(language => language.code === saved)) {
		return saved;
	}

	return 'en';
}

export function setLanguage(language: string) {
	strings.setLanguage(language);
	localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
}

